/**
 * Emit a Markdown reference for everything the game actually implements.
 *
 *   npm run reference           # write docs/reference/*.md
 *   npm run reference -- --check  # fail if the files on disk are stale
 *
 * The point is that this is *derived*, never written by hand. Hand-kept content
 * lists rot silently — docs/SPEC.md has claimed a wrong monster count more than
 * once — and the failure is invisible because nothing reads them. Here the data
 * modules are the single source of truth and these files are their printout, so
 * "the docs are wrong" becomes a failing test rather than something a reader
 * discovers.
 *
 * What is emitted is what the engine can see: declared fields, plus the few
 * numbers derived the same way the engine derives them (a monster's XP, its
 * proficiency bonus, a class's slot table). Behaviour that lives inside a
 * `cast` or `apply` closure is deliberately NOT paraphrased — a summary of code
 * is the kind of thing that goes stale without anyone noticing, which is the
 * problem this script exists to solve. Where the effect cannot be read off the
 * data, the row says how it is aimed and leaves the rest to the source.
 */
