function classesDoc(): string {
  const all = Object.values(CLASSES).sort(byName);
  const maxLevel = Math.max(...all.map((c) => Math.max(...Object.keys(c.featuresByLevel).map(Number))));

  const sections = all.map((c) => {
    const lines = [
      `## ${c.name}`,
      '',
      `\`${c.id}\` · d${c.hitDie} hit die · saves ${c.savingThrows.map((s) => s.toUpperCase()).join(' & ')}`,
      '',
      `- **Armor:** ${cell(c.armorProfs)}`,
      `- **Skills offered:** ${c.skillProfs.map((s) => SKILL_LABEL[s]).join(', ')}`,
      `- **Ability priority:** ${c.statPriority.map((a) => a.toUpperCase()).join(' > ')}`,
      `- **Weapon masteries:** ${cell(c.weaponMasteries.map((w) => WEAPONS[w]?.name ?? w))}`,
      `- **Starting kit:** ${[
        WEAPONS[c.equipment.mainHand]?.name ?? c.equipment.mainHand,
        c.equipment.offHand === 'shield' ? 'shield' : c.equipment.offHand ? WEAPONS[c.equipment.offHand]?.name ?? c.equipment.offHand : '',
        c.equipment.armor ? ARMOR[c.equipment.armor]?.name ?? c.equipment.armor : '',
        // A starting pack holds spare weapons as well as potions, so the id
        // has to be looked up in both tables.
        ...c.equipment.inventory.map((s) => `${ITEMS[s.itemId]?.name ?? WEAPONS[s.itemId]?.name ?? s.itemId} ×${s.qty}`),
      ].filter(Boolean).join(', ')}`,
      '',
      '### Features by level',
      '',
      table(['Level', 'Features'], Object.entries(c.featuresByLevel)
        .sort((a, b) => Number(a[0]) - Number(b[0]))
        .map(([lvl, ids]) => [lvl, ids.map((f) => FEATURES[f]?.name ?? f).join(', ')])),
      '',
    ];

    if (c.spellcasting) {
      const sc = c.spellcasting;
      lines.push('### Spell slots', '');
      const widest = Math.max(...sc.slotsByLevel.map((r) => r.length));
      lines.push(table(
        ['Level', ...Array.from({ length: widest }, (_, i) => `${i + 1}${['st', 'nd', 'rd', 'th'][Math.min(i, 3)]}`),
          ...(sc.cantripsKnownByLevel ? ['Cantrips'] : []),
          ...(sc.spellbookByLevel ? ['Spellbook'] : []),
          ...(sc.preparedByLevel ? ['Prepared'] : [])],
        sc.slotsByLevel.map((row, i) => [
          i + 1,
          ...Array.from({ length: widest }, (_, j) => row[j] ?? '—'),
          ...(sc.cantripsKnownByLevel ? [sc.cantripsKnownByLevel[i] ?? '—'] : []),
          ...(sc.spellbookByLevel ? [sc.spellbookByLevel[i] ?? '—'] : []),
          ...(sc.preparedByLevel ? [sc.preparedByLevel[i] ?? '—'] : []),
        ]),
      ), '');
      lines.push(`Spellcasting ability: **${sc.ability.toUpperCase()}**.`, '');
      lines.push('### Spell list', '',
        // Keyed by CHARACTER level — the level at which the spells arrive —
        // not by spell level. Labelling it "Level" invites exactly the wrong
        // reading, since every other slot table on the page means spell level.
        table(['Arrives at character level', 'Spells (in priority order — the auto-loadout takes the first few)'],
          Object.entries(sc.spellsByLevel).sort((a, b) => Number(a[0]) - Number(b[0]))
            .map(([lvl, ids]) => [lvl, ids.map((s) => SPELLS[s]?.name ?? s).join(', ')])), '');
      if (sc.learnableExtra?.length) {
        lines.push(`Learnable from scrolls found in play: ${sc.learnableExtra.map((s) => SPELLS[s]?.name ?? s).join(', ')}.`, '');
      }
    }

    for (const cp of c.choices ?? []) {
      lines.push(`### Choice: ${cp.label} (level ${cp.atLevel})`, '',
        table(['Option', 'Grants', 'Blurb'], cp.options.map((o) => [
          o.id === cp.default ? `${o.name} *(default)*` : o.name,
          [
            ...(o.grants.featureIds ?? []).map((f) => FEATURES[f]?.name ?? f),
            ...(o.grants.spellIds ?? []).map((s) => SPELLS[s]?.name ?? s),
            ...(o.grants.weaponMasteries ?? []).map((w) => `mastery: ${WEAPONS[w]?.name ?? w}`),
            ...(o.grants.resistances ?? []).map((r) => `resist ${r}`),
          ].join(', '),
          o.blurb,
        ])), '');
    }
    return lines.join('\n');
  });

  return [
    preamble('Classes', `${all.length} playable classes, levels 1–${maxLevel}.`),
    ...sections,
  ].join('\n');
}

