// --- small formatting helpers ----------------------------------------------

/** A Markdown table cell: em dash for nothing, so columns never collapse. */
function cell(v: unknown): string {
  if (v === undefined || v === null || v === '' || (Array.isArray(v) && v.length === 0)) return '—';
  if (Array.isArray(v)) return v.join(', ');
  if (typeof v === 'boolean') return v ? 'yes' : '—';
  return String(v).replace(/\|/g, '\\|');
}

function table(headers: string[], rows: unknown[][]): string {
  const head = `| ${headers.join(' | ')} |`;
  const rule = `| ${headers.map(() => '---').join(' | ')} |`;
  const body = rows.map((r) => `| ${r.map(cell).join(' | ')} |`).join('\n');
  return [head, rule, body].join('\n');
}

const byName = <T extends { name: string }>(a: T, b: T): number => a.name.localeCompare(b.name);

function signed(n: number): string {
  return n >= 0 ? `+${n}` : String(n);
}

/** The header every generated file carries, so nobody edits one by hand. */
function preamble(title: string, note: string): string {
  return [
    `# ${title}`,
    '',
    '> Generated by `npm run reference` from the data modules in `src/data/`.',
    '> Do not edit by hand — edit the data and regenerate.',
    '',
    note,
    '',
  ].join('\n');
}

// --- monsters ---------------------------------------------------------------

/** How a monster's stat block reads at the table: "Str 16 (+3)". */
function abilityLine(m: MonsterData): string {
  return (['str', 'dex', 'con', 'int', 'wis', 'cha'] as const)
    .map((a) => `${a.toUpperCase()} ${m.abilities[a]} (${signed(abilityMod(m.abilities[a]))})`)
    .join(', ');
}

function monsterAttacks(m: MonsterData): string {
  return m.weaponIds
    .map((wid) => {
      const w = WEAPONS[wid];
      if (!w) return wid;
      const bits = [`${w.name} ${w.damage} ${w.damageType}`];
      if (w.range) bits.push(`${w.range.normal}/${w.range.long} ft`);
      else if (!w.melee) bits.push('ranged');
      if (w.onHitCondition) bits.push(`on hit: ${w.onHitCondition}`);
      if (w.onHitSave) bits.push(`${w.onHitSave.ability.toUpperCase()} DC ${w.onHitSave.dc} or ${w.onHitSave.condition}`);
      if (w.extraDamage) bits.push(`+${w.extraDamage.dice} ${w.extraDamage.type}`);
      if (w.slays) bits.push(`+${w.slays.dice} vs ${w.slays.types.join('/')}`);
      return bits.join(', ');
    })
    .join('; ');
}

function monstersDoc(): string {
  const all = Object.values(MONSTERS).sort((a, b) => (MONSTER_XP[a.id] ?? 0) - (MONSTER_XP[b.id] ?? 0) || a.name.localeCompare(b.name));
  const casters = all.filter((m) => m.spellcasting);

  const rows = all.map((m) => [
    m.name,
    `\`${m.id}\``,
    m.creatureType,
    MONSTER_XP[m.id] ?? 0,
    m.cr ?? '≤4',
    m.ac,
    m.hp,
    `${m.speed} ft`,
    m.attacksPerAction ?? 1,
    canThreatenAtRange(m.id) ? 'yes' : '—',
    m.minPartyLevel ?? '—',
  ]);

  const detail = all
    .map((m) => {
      const lines: string[] = [`### ${m.name}`, '', `\`${m.id}\` · ${m.creatureType} · ${MONSTER_XP[m.id] ?? 0} XP · AC ${m.ac} · ${m.hp} HP · ${m.speed} ft · PB ${signed(proficiencyBonus(monsterLevel(m.cr)))}`, '', abilityLine(m), ''];
      const add = (label: string, v: unknown) => {
        if (v === undefined || (Array.isArray(v) && v.length === 0)) return;
        lines.push(`- **${label}:** ${cell(v)}`);
      };
      add('Saving throws', m.savingThrowProfs?.map((s) => s.toUpperCase()));
      add('Attacks', monsterAttacks(m));
      add('Features', m.featureIds?.map((f) => FEATURES[f]?.name ?? f));
      add('Resistances', m.resistances);
      add('Resists nonmagical', m.resistNonmagical);
      add('Immunities', m.immunities);
      add('Vulnerabilities', m.vulnerabilities);
      if (m.regeneration) add('Regeneration', `${m.regeneration.amount}/turn, stopped by ${m.regeneration.stoppedBy.join('/')}`);
      if (m.holdDamage) add('Hold damage', `${m.holdDamage.dice} ${m.holdDamage.type} to whoever it has restrained`);
      if (m.deathBurst) add('Death burst', `${m.deathBurst.dice} ${m.deathBurst.type}, ${m.deathBurst.save.ability.toUpperCase()} DC ${m.deathBurst.save.dc}, ${m.deathBurst.radius} ft`);
      if (m.spellcasting) {
        const slots = m.spellcasting.slots.map((n, i) => `${n}×L${i + 1}`).join(' ');
        add('Spellcasting', `${m.spellcasting.ability.toUpperCase()}, slots ${slots || 'none'}`);
        add('Spells', m.spellcasting.spellIds.map((s) => SPELLS[s]?.name ?? s));
      }
      if (m.minPartyLevel) add('Held back until party level', m.minPartyLevel);
      if (m.metalArmor) add('Metal armor', 'yes (Shocking Grasp rider)');
      lines.push('');
      return lines.join('\n');
    })
    .join('\n');

  return [
    preamble('Monsters', `${all.length} monsters, ${casters.length} of them spellcasters. Sorted by XP.`),
    '## At a glance',
    '',
    table(
      ['Name', 'ID', 'Type', 'XP', 'CR', 'AC', 'HP', 'Speed', 'Attacks', 'Ranged?', 'Min party lvl'],
      rows,
    ),
    '',
    '## Stat blocks',
    '',
    detail,
  ].join('\n');
}

// --- spells -----------------------------------------------------------------

/** How a spell is aimed, in words — derived from `targeting`, never hand-kept. */
function aiming(t: SpellTargeting): string {
  switch (t.kind) {
    case 'creature': {
      const who = t.who === 'any' ? 'creature' : t.who;
      const n = t.count > 1 ? `${t.count} ${who}s` : `1 ${who}`;
      const types = t.creatureType ? ` (${t.creatureType} only)` : t.creatureTypes ? ` (${t.creatureTypes.join('/')} only)` : '';
      // Range 0 is a touch spell, and "within 0 ft" reads as a bug.
      const reach = t.range === 0 ? 'you can touch' : `within ${t.range} ft`;
      return `${n} ${reach}${types}`;
    }
    case 'weaponAttack': return 'the weapon in hand (its own reach)';
    case 'sphere2x2': return `2×2 burst within ${t.range} ft`;
    case 'sphere5x5': return `5×5 burst within ${t.range} ft`;
    case 'cone15': return '15 ft cone';
    case 'cube15': return '15 ft cube (adjacent)';
    case 'line15': return 'line to the board edge';
    case 'emptyCell': return `an empty cell within ${t.range} ft`;
    case 'self': return t.anyTime ? 'self (castable any time)' : 'self (offered when it would reach someone)';
  }
}

/** Every class list a spell appears on, and the level it arrives. */
function spellSources(): Map<string, string[]> {
  const out = new Map<string, string[]>();
  const push = (id: string, src: string) => {
    const list = out.get(id) ?? [];
    if (!list.includes(src)) list.push(src);
    out.set(id, list);
  };
  for (const c of Object.values(CLASSES)) {
    for (const [lvl, ids] of Object.entries(c.spellcasting?.spellsByLevel ?? {})) {
      for (const id of ids) push(id, `${c.name} ${lvl}`);
    }
    for (const id of c.spellcasting?.learnableExtra ?? []) push(id, `${c.name} (scroll)`);
  }
  for (const s of Object.values(SPECIES)) {
    for (const ids of Object.values(s.spellsByLevel ?? {})) for (const id of ids) push(id, s.name);
    for (const inn of s.innateSpells ?? []) push(inn.spellId, s.name);
  }
  for (const m of Object.values(MONSTERS)) {
    for (const id of m.spellcasting?.spellIds ?? []) push(id, m.name);
  }
  return out;
}

function spellsDoc(): string {
  const all = Object.values(SPELLS).sort((a, b) => a.level - b.level || a.name.localeCompare(b.name));
  const sources = spellSources();
  const counts = new Map<number, number>();
  for (const s of all) counts.set(s.level, (counts.get(s.level) ?? 0) + 1);
  const tally = [...counts].sort((a, b) => a[0] - b[0])
    .map(([lvl, n]) => `${lvl === 0 ? 'cantrips' : `level ${lvl}`}: ${n}`).join(', ');

  const sections = [...counts.keys()].sort((a, b) => a - b).map((lvl) => {
    const at = all.filter((s) => s.level === lvl);
    const rows = at.map((s: SpellData) => [
      `${s.icon} ${s.name}`,
      `\`${s.id}\``,
      s.castingTime,
      aiming(s.targeting),
      s.concentration ? 'yes' : '—',
      s.upcast ? 'yes' : '—',
      [s.ritual ? 'ritual' : '', s.outOfCombat ? 'out of combat' : ''].filter(Boolean).join(', ') || '—',
      (sources.get(s.id) ?? []).join(', ') || '—',
    ]);
    return [
      `## ${lvl === 0 ? 'Cantrips' : `Level ${lvl}`}`,
      '',
      table(['Spell', 'ID', 'Cast', 'Aimed at', 'Conc.', 'Upcast', 'Notes', 'Known by'], rows),
      '',
    ].join('\n');
  });

  return [
    preamble('Spells', [
      `${all.length} spells — ${tally}.`,
      '',
      '**Upcast** marks a spell `legalActions` offers at every slot the caster can',
      'afford, because its effect scales. Anything unmarked is offered at its own',
      'level only, and spending a bigger slot on it would buy nothing.',
      '',
      '**Aimed at** is derived from the spell\'s `targeting`, so it is always true.',
      'What the spell *does* lives in its `cast` closure and is not paraphrased here —',
      'see `src/data/spells.ts`.',
    ].join('\n')),
    ...sections,
  ].join('\n');
}

