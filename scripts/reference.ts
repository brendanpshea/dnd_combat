function featuresDoc(): string {
  const all = Object.values(FEATURES).sort(byName);
  const usesOf = (f: (typeof all)[number]): string => {
    // "Recharge 5–6" and "Recharge 6" — a range of one is written as one.
    if (f.recharge) return f.recharge >= 6 ? 'recharge 6' : `recharge ${f.recharge}–6`;
    if (!f.uses) return '—';
    // The clock in prose, not in the enum's spelling: this table is read by a
    // person deciding whether a feature is a per-fight trick or the day's
    // budget, and `1/shortRest` makes them stop and parse an identifier.
    const clock = { encounter: 'fight', shortRest: 'short rest', longRest: 'long rest' }[f.uses.per];
    return `${f.uses.count}/${clock}`;
  };
  return [
    preamble('Features', [
      `${all.length} features — class abilities, species traits, monster traits and trinket grants,`,
      'all in one namespace because the engine resolves them the same way.',
      '',
      '`Trigger` is how it is taken: an action, a bonus action, `free` (rider on',
      'something else) or `passive` (always on).',
    ].join('\n')),
    table(
      ['Name', 'ID', 'Trigger', 'Uses', 'Adv. dice', 'Notes'],
      all.map((f) => [
        f.name, `\`${f.id}\``, f.trigger, usesOf(f),
        f.advantageDice ? f.advantageDice(5) + ' (at level 5)' : '—',
        [
          f.manualUses ? 'spends its own pool' : '',
          BREATH_WEAPONS[f.id]
          ? (() => {
              const b = BREATH_WEAPONS[f.id]!;
              const shape = b.shape === 'line' ? `${(b.length ?? 0) * 5} ft line` : '15 ft cone';
              return `${shape}, ${b.dice} ${b.damageType}, ${b.save.toUpperCase()} save`;
            })()
          : '',
          !f.apply ? 'read by the rules, no action of its own' : '',
        ].filter(Boolean).join('; '),
      ]),
    ),
    '',
    '## Conditions',
    '',
    'What the engine can put on a combatant, and what the log calls it.',
    '',
    table(['ID', 'Log name'], Object.entries(CONDITION_NAME).sort().map(([id, name]) => [`\`${id}\``, name])),
    '',
  ].join('\n');
}

// --- content ----------------------------------------------------------------

function contentDoc(): string {
  const encounters = Object.values(ENCOUNTERS).sort((a, b) => a.suggestedLevel - b.suggestedLevel || a.name.localeCompare(b.name));
  const maps = Object.values(MAPS).sort(byName);
  const modules = [...MODULES].sort((a, b) => a.title.localeCompare(b.title));
  // Two of the five are test scaffolding kept out of the player's menu; the
  // reference lists them, but says which is which.
  const shipped = new Set(playableModules(false).map((m) => m.id));

  const encounterXp = (m: string[]): number => m.reduce((s, id) => s + (MONSTER_XP[id] ?? 0), 0);
  const roster = (m: string[]): string => {
    const counts = new Map<string, number>();
    for (const id of m) counts.set(id, (counts.get(id) ?? 0) + 1);
    return [...counts].map(([id, n]) => `${n}× ${MONSTERS[id]?.name ?? id}`).join(', ');
  };

  return [
    preamble('Encounters, Maps & Modules', `${encounters.length} hand-built encounters, ${maps.length} maps, ${modules.length} adventure modules.`),
    '## Encounters',
    '',
    'Hand-built fights. The arena generates its own from an XP budget instead — see `src/arena/encounter.ts`.',
    '',
    table(
      ['Name', 'ID', 'Suggested level', 'Total XP', 'Roster'],
      encounters.map((e) => [e.name, `\`${e.id}\``, e.suggestedLevel, encounterXp(e.members), roster(e.members)]),
    ),
    '',
    '## Maps',
    '',
    table(
      ['Name', 'ID', 'Theme', 'Size', 'Walls', 'Difficult', 'Hazard'],
      maps.map((m) => {
        const grid = parseMap(m);
        const count = (t: string) => grid.cells.filter((c) => c.terrain === t).length;
        return [m.name, `\`${m.id}\``, m.theme, `${grid.width}×${grid.height}`, count('wall'), count('difficult'), count('hazard')];
      }),
    ),
    '',
    '## Adventure modules',
    '',
    table(
      ['Title', 'ID', 'Levels', 'Scenes', 'Sequel', 'Shown in the menu', 'Blurb'],
      modules.map((m) => [
        m.title,
        `\`${m.id}\``,
        m.levelBand ? `${m.levelBand.from}–${m.levelBand.to}` : '—',
        Object.keys(m.scenes).length,
        m.sequel ?? '—',
        shipped.has(m.id) ? 'yes' : 'dev only',
        m.blurb,
      ]),
    ),
    '',
  ].join('\n');
}

// --- index ------------------------------------------------------------------

function indexDoc(files: Array<{ file: string; title: string; summary: string }>): string {
  const spellCount = Object.keys(SPELLS).length;
  const maxLevel = Math.max(...Object.values(CLASSES).flatMap((c) => Object.keys(c.featuresByLevel).map(Number)));
  return [
    preamble('Content Reference', [
      'Everything the game implements, printed from the data modules.',
      '',
      `**${Object.keys(MONSTERS).length}** monsters · **${spellCount}** spells ·`,
      `**${Object.keys(CLASSES).length}** classes (levels 1–${maxLevel}) ·`,
      `**${Object.keys(SPECIES).length}** species · **${Object.keys(FEATURES).length}** features ·`,
      `**${Object.keys(WEAPONS).length}** weapons · **${Object.keys(ITEMS).length}** consumables ·`,
      `**${Object.keys(ENCOUNTERS).length}** encounters · **${Object.keys(MAPS).length}** maps`,
    ].join('\n')),
    table(['File', 'Contents'], files.map((f) => [`[${f.title}](./${f.file})`, f.summary])),
    '',
    '## Regenerating',
    '',
    '```sh',
    'npm run reference            # rewrite these files',
    'npm run reference -- --check # fail if they are stale (CI does this)',
    '```',
    '',
  ].join('\n');
}

// --- driver -----------------------------------------------------------------

const FILES: Array<{ file: string; title: string; summary: string; build: () => string }> = [
  { file: 'monsters.md', title: 'Monsters', summary: 'Every stat block: abilities, attacks, features, spell kits, XP.', build: monstersDoc },
  { file: 'spells.md', title: 'Spells', summary: 'Every spell by level, how it is aimed, whether it upcasts, and who knows it.', build: spellsDoc },
  { file: 'gear.md', title: 'Gear', summary: 'Weapons, armor, consumables, trinkets and valuables.', build: gearDoc },
  { file: 'classes.md', title: 'Classes', summary: 'Per class: proficiencies, features by level, slot table, spell list, choices.', build: classesDoc },
  { file: 'characters.md', title: 'Species & Backgrounds', summary: 'Species traits and innate magic; background skills.', build: charactersDoc },
  { file: 'features.md', title: 'Features & Conditions', summary: 'Every named feature and every condition the engine can apply.', build: featuresDoc },
  { file: 'content.md', title: 'Encounters, Maps & Modules', summary: 'Hand-built fights, map terrain counts, adventure modules.', build: contentDoc },
];

function render(): Map<string, string> {
  const out = new Map<string, string>();
  for (const f of FILES) out.set(f.file, f.build().trimEnd() + '\n');
  out.set('README.md', indexDoc(FILES).trimEnd() + '\n');
  return out;
}

const check = process.argv.includes('--check');
const rendered = render();

if (check) {
  const stale: string[] = [];
  for (const [file, body] of rendered) {
    const path = join(OUT, file);
    if (!existsSync(path) || readFileSync(path, 'utf8') !== body) stale.push(file);
  }
  if (stale.length > 0) {
    console.error(`Reference docs are stale: ${stale.join(', ')}`);
    console.error('Run `npm run reference` and commit the result.');
    process.exit(1);
  }
  console.log(`Reference docs are up to date (${rendered.size} files).`);
} else {
  mkdirSync(OUT, { recursive: true });
  for (const [file, body] of rendered) {
    const path = join(OUT, file);
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, body);
    console.log(`${path}  (${body.split('\n').length} lines)`);
  }
}
